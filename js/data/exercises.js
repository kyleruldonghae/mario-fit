export const EX_BY_ID = Object.fromEntries(EXERCISES.map((e) => [e.id, e]));

export function exName(ex, settings) {
  if (!ex) return 'Unknown exercise';
  return settings?.namesFirst === 'en' ? `${ex.en}` : `${ex.de}`;
}
export function exSub(ex, settings) {
  if (!ex) return '';
  return settings?.namesFirst === 'en' ? ex.de : ex.en;
}
